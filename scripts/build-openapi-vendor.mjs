// Run after npm ci; the shipped extension imports this local browser bundle.
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const pkg = JSON.parse(
  await readFile(new URL('../node_modules/yaml/package.json', import.meta.url), 'utf8'),
);
await mkdir(new URL('../extension/vendor/', import.meta.url), { recursive: true });
await build({
  absWorkingDir: root,
  stdin: {
    contents: "export { parseDocument } from 'yaml';",
    resolveDir: root,
    sourcefile: 'yaml-browser-entry.js',
  },
  outfile: 'extension/vendor/yaml.js',
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'chrome114',
  minify: true,
  legalComments: 'none',
  banner: {
    js: `// yaml ${pkg.version}; ISC license. See yaml.LICENSE.txt. Generated by npm run build:openapi.`,
  },
});
await writeFile(
  new URL('../extension/vendor/yaml.LICENSE.txt', import.meta.url),
  await readFile(new URL('../node_modules/yaml/LICENSE', import.meta.url)),
);
console.log(`Bundled yaml ${pkg.version} for the offline extension.`);
